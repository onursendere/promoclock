// @ts-check
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile, mkdir, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

/** Third parties the pages talk to: Google Analytics (only after consent) and Cloudflare Web Analytics. */
const ANALYTICS = {
  script: ["https://www.googletagmanager.com", "https://static.cloudflareinsights.com"],
  connect: [
    "https://*.google-analytics.com",
    "https://*.analytics.google.com",
    "https://*.googletagmanager.com",
    "https://cloudflareinsights.com",
  ],
  img: ["https://*.google-analytics.com", "https://*.googletagmanager.com"],
};

const JS_TYPES = new Set(["", "module", "text/javascript", "application/javascript"]);

/**
 * Content-Security-Policy without 'unsafe-inline' scripts: every inline <script> the build emitted
 * (theme bootstrap, Astro island loaders, …) is allowed by its SHA-256 hash, so the policy always
 * matches the pages it ships with. Fails the build on inline event handlers or javascript: URLs,
 * which a hash-based policy would silently block.
 *
 * @param {string} outDir
 */
async function contentSecurityPolicy(outDir) {
  const files = (await readdir(outDir, { recursive: true })).filter((f) => f.endsWith(".html"));
  const hashes = new Set();
  for (const file of files) {
    const html = await readFile(path.join(outDir, file), "utf8");
    if (/<[a-z][^>]*\son[a-z]+\s*=\s*["']/i.test(html) || /\shref\s*=\s*["']\s*javascript:/i.test(html)) {
      throw new Error(`${file}: inline event handler or javascript: URL — the CSP would block it`);
    }
    for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
      if (/\ssrc\s*=/i.test(attrs) || !body) continue;
      const type = attrs.match(/\stype\s*=\s*["']?([^"'\s>]+)/i)?.[1]?.toLowerCase() ?? "";
      if (!JS_TYPES.has(type)) continue;
      hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
    }
  }
  const policy = [
    "default-src 'self'",
    `script-src 'self' ${[...hashes].sort().join(" ")} ${ANALYTICS.script.join(" ")}`,
    "style-src 'self' 'unsafe-inline'",
    `img-src 'self' data: ${ANALYTICS.img.join(" ")}`,
    "font-src 'self'",
    `connect-src 'self' ${ANALYTICS.connect.join(" ")}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'self'",
    "upgrade-insecure-requests",
  ].join("; ");
  return { policy, hashCount: hashes.size, pageCount: files.length };
}

/**
 * Writes dist/.htaccess for Apache/LiteSpeed (cPanel) after the static build:
 * HTTPS, language redirect for "/", the /api/status rewrite, legacy /go/<slug>/ 301s built
 * from dist/go/redirects.json (deleted afterwards), caching, compression and security headers
 * (HSTS, a hash-based CSP, COOP/COEP/CORP).
 *
 * @param {{ locales: readonly string[]; defaultLocale: string; staging?: boolean }} options
 * @returns {import("astro").AstroIntegration}
 */
export default function cpanelHtaccess({ locales, defaultLocale, staging = false }) {
  return {
    name: "promoclock:cpanel-htaccess",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const outDir = fileURLToPath(dir);
        const redirectsFile = path.join(outDir, "go/redirects.json");
        /** @type {{ slug: string; target: string }[]} */
        const tools = JSON.parse(await readFile(redirectsFile, "utf8"));
        await rm(redirectsFile);

        const csp = await contentSecurityPolicy(outDir);
        const nonDefault = locales.filter((l) => l !== defaultLocale && !l.includes("-"));
        const regional = locales.filter((l) => l.includes("-"));
        const localeAlternation = locales.map((l) => l.replace(/[-]/g, "\\-")).join("|");

        const lines = [
          "# Generated by integrations/cpanel-htaccess.mjs at build time — edit the generator, not this file.",
          "Options -Indexes",
          "DirectoryIndex index.html index.php",
          "ErrorDocument 404 /404.html",
          "AddDefaultCharset utf-8",
          "AddCharset utf-8 .txt .json .xml .html",
          "",
          "<IfModule mod_rewrite.c>",
          "  RewriteEngine On",
          "  RewriteBase /",
          "",
          "  # Force HTTPS (Cloudflare terminates TLS and sends X-Forwarded-Proto / CF-Visitor).",
          "  RewriteCond %{HTTPS} !=on",
          "  RewriteCond %{HTTP:X-Forwarded-Proto} !=https",
          "  RewriteCond %{HTTP:CF-Visitor} !https",
          "  RewriteCond %{HTTP_HOST} !^(localhost|127\\.0\\.0\\.1) [NC]",
          "  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]",
          "",
          "  # Hide dotfiles and the API's internal files.",
          "  RewriteRule (^|/)\\.(?!well-known/) - [F,L]",
          "  RewriteRule ^api/(_|claude\\.json$) - [F,L]",
          "",
          "  # JSON API (PHP): only the Claude peak-hours status is public.",
          "  RewriteRule ^api/status/?$ api/status.php [L,QSA]",
          "  # Retired endpoints.",
          "  RewriteRule ^api/(deals(\\.php|\\.json)?|tools\\.json)/?$ - [G,L]",
          "",
          "  # Retired /go/<slug>/ outbound links: pages link straight to the tool's site now. Old URLs move",
          "  # permanently to the tool's English profile, never off-site: Google reports a redirect by its",
          "  # destination, and a vendor's noindex or 403 page would keep them in Search Console's exclusions.",
          ...tools.map((t) => `  RewriteRule ^go/${t.slug}/?$ ${t.target} [R=301,L]`),
          "",
          "  # Legacy URLs from the Next.js site.",
          "  RewriteRule ^sitemap\\.xml$ /sitemap-index.xml [R=301,L]",
          "",
          "  # Unprefixed section paths → English.",
          `  RewriteRule ^(deals|tools|calendar|affiliate-disclosure|privacy|about|blog)/?$ /${defaultLocale}/$1/ [R=301,L]`,
          `  RewriteRule ^(deals|tools|calendar|affiliate-disclosure|privacy|about|blog)(/.+)$ /${defaultLocale}/$1$2 [R=301,L]`,
          "",
          "  # Root → saved language, then browser language, then English.",
          `  RewriteCond %{HTTP_COOKIE} (?:^|;\\s*)(?:NEXT_)?LOCALE=(${localeAlternation})(?:;|$)`,
          "  RewriteRule ^$ /%1/ [R=302,L]",
          ...regional.flatMap((l) => [
            `  RewriteCond %{HTTP:Accept-Language} ^${l.split("-")[0]} [NC]`,
            `  RewriteRule ^$ /${l}/ [R=302,L]`,
          ]),
          `  RewriteCond %{HTTP:Accept-Language} ^(${nonDefault.join("|")}) [NC]`,
          "  RewriteRule ^$ /%1/ [R=302,L]",
          `  RewriteRule ^$ /${defaultLocale}/ [R=302,L]`,
          "</IfModule>",
          "",
          "<IfModule mod_headers.c>",
          '  Header always set X-Content-Type-Options "nosniff"',
          '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
          '  Header always set X-Frame-Options "SAMEORIGIN"',
          '  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"',
          '  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"',
          `  Header always set Content-Security-Policy "${csp.policy}"`,
          '  Header always set Cross-Origin-Opener-Policy "same-origin"',
          // credentialless: cross-origin isolation without requiring CORP from Google/Cloudflare scripts.
          '  Header always set Cross-Origin-Embedder-Policy "credentialless"',
          '  Header always set Cross-Origin-Resource-Policy "same-site"',
          ...(staging ? ['  Header always set X-Robots-Tag "noindex, nofollow"'] : []),
          "  # Files other sites and apps may load: images (share cards, logo), feeds, llms.txt and the JSON API.",
          '  <FilesMatch "\\.(png|jpe?g|webp|avif|gif|svg|ico|txt|xml|json|webmanifest|php)$">',
          '    Header always set Cross-Origin-Resource-Policy "cross-origin"',
          "  </FilesMatch>",
          '  <FilesMatch "\\.html$">',
          '    Header set Cache-Control "public, max-age=0, must-revalidate"',
          "    # Edge-only lifetime: Cloudflare caches pages for an hour and keeps answering from cache while it",
          "    # refreshes in the background (or while the origin is down), then strips this header, so browsers",
          "    # still revalidate on every load. Deploys purge the edge; the hour only bounds a missed purge.",
          '    Header set Cloudflare-CDN-Cache-Control "max-age=3600, stale-while-revalidate=86400, stale-if-error=86400"',
          "  </FilesMatch>",
          '  <FilesMatch "\\.(txt|xml|json)$">',
          '    Header set Cache-Control "public, max-age=3600"',
          "  </FilesMatch>",
          '  <FilesMatch "\\.(png|ico|svg|webp|woff2)$">',
          '    Header set Cache-Control "public, max-age=604800"',
          "  </FilesMatch>",
          "</IfModule>",
          "",
          "<IfModule mod_deflate.c>",
          "  AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml application/javascript application/json application/xml image/svg+xml",
          "</IfModule>",
          "",
        ];

        await writeFile(path.join(outDir, ".htaccess"), lines.join("\n"), "utf8");

        // Hashed build assets never change.
        await mkdir(path.join(outDir, "_astro"), { recursive: true });
        await writeFile(
          path.join(outDir, "_astro/.htaccess"),
          [
            "<IfModule mod_headers.c>",
            '  Header set Cache-Control "public, max-age=31536000, immutable"',
            "</IfModule>",
            "",
          ].join("\n"),
          "utf8",
        );

        logger.info(
          `.htaccess written with ${tools.length} legacy /go/ redirects and a CSP of ${csp.hashCount} inline-script hashes from ${csp.pageCount} pages${staging ? " (staging)" : ""}`,
        );
      },
    },
  };
}
